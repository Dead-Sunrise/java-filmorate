CREATE TABLE IF NOT EXISTS genres (
id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR(64)
);

CREATE TABLE IF NOT EXISTS mpa_ratings (
id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS directors (
director_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS films (
id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR(64) NOT NULL,
description VARCHAR(200),
release_date DATE,
duration INTEGER,
mpa_id INTEGER REFERENCES mpa_ratings (id),
director_id INTEGER REFERENCES directors (director_id)
);

CREATE TABLE IF NOT EXISTS users (
id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
email VARCHAR(64) UNIQUE,
login VARCHAR(64) NOT NULL UNIQUE,
name VARCHAR (64),
birthday DATE
);

CREATE TABLE IF NOT EXISTS film_genre (
film_id INTEGER REFERENCES films (id) ON DELETE CASCADE,
genre_id INTEGER REFERENCES genres (id),
PRIMARY KEY (film_id, genre_id)
);

CREATE TABLE IF NOT EXISTS friends (
user_id INTEGER REFERENCES users (id) ON DELETE CASCADE,
friend_id INTEGER REFERENCES users (id) ON DELETE CASCADE,
PRIMARY KEY (user_id, friend_id)
);

CREATE TABLE IF NOT EXISTS film_likes (
film_id INTEGER REFERENCES films (id) ON DELETE CASCADE,
user_id INTEGER REFERENCES users (id) ON DELETE CASCADE,
PRIMARY KEY (film_id, user_id)
);

CREATE TABLE IF NOT EXISTS reviews (
    review_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message VARCHAR(1000) NOT NULL,
    is_positive BOOLEAN NOT NULL,
    user_id INTEGER REFERENCES users (id) ON DELETE CASCADE,
    film_id INTEGER REFERENCES films (id) ON DELETE CASCADE,
    useful INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS review_likes (
    review_id INTEGER REFERENCES reviews (review_id) ON DELETE CASCADE,
    user_id INTEGER REFERENCES users (id) ON DELETE CASCADE,
    is_like BOOLEAN NOT NULL,
    PRIMARY KEY (review_id, user_id)
);

CREATE TABLE IF NOT EXISTS event_type (
    type_id INTEGER PRIMARY KEY,
    name VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS event_operation (
    operation_id INTEGER PRIMARY KEY,
    name VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS event_feed (
    event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users (id) ON DELETE CASCADE,
    type_id INTEGER REFERENCES event_type (type_id),
    operation_id INTEGER REFERENCES event_operation (operation_id),
    entity_id INTEGER NOT NULL,
    time TIMESTAMP
);

MERGE INTO event_type (type_id, name)
VALUES  (1, 'LIKE'),
        (2, 'REVIEW'),
        (3, 'FRIEND');

MERGE INTO event_operation (operation_id, name)
VALUES  (1, 'REMOVE'),
        (2, 'ADD'),
        (3, 'UPDATE');